CREATE TABLE IF NOT EXISTS clientes (
    id                        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cedula                    varchar(12)  NOT NULL,
    nombre                    varchar(200) NOT NULL,
    correo                    varchar(200) NOT NULL,
    intentos_fallidos         integer      NOT NULL DEFAULT 0,
    bloqueado_hasta           timestamptz,
    token_recuperacion_hash   varchar(64),
    token_recuperacion_vence  timestamptz,
    creado_en                 timestamptz  NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS ix_clientes_cedula ON clientes (cedula);
-- Las claves ya no viven en clientes (antes bcrypt): ahora están en el directorio activo, en texto plano.
ALTER TABLE clientes DROP COLUMN IF EXISTS clave_hash;

-- Directorio activo de YoPago: cédula + clave SIN cifrar (decisión deliberada, ver DirectorioActivoService).
CREATE TABLE IF NOT EXISTS directorio_activo (
    cedula varchar(12)  PRIMARY KEY,
    clave  varchar(100) NOT NULL
);

CREATE TABLE IF NOT EXISTS compras (
    id               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero_compra    varchar(40)   NOT NULL,
    cliente_id       integer       NOT NULL REFERENCES clientes (id),
    descripcion      varchar(300)  NOT NULL,
    codigo_subasta   varchar(40),
    valor_oferta     numeric(18,2) NOT NULL,
    impuestos        numeric(18,2) NOT NULL,
    comision         numeric(18,2) NOT NULL,
    valor_total      numeric(18,2) NOT NULL,
    recibida_en      timestamptz   NOT NULL,
    vence_en         timestamptz,
    pagada_en        timestamptz,
    sincronizada_en  timestamptz   NOT NULL,
    estado           varchar(20)   NOT NULL,
    CONSTRAINT ck_compras_estado CHECK (estado IN ('Pendiente', 'Pagada', 'Rechazada')),
    CONSTRAINT ck_compras_valor_total CHECK (valor_total > 0)
);
CREATE UNIQUE INDEX IF NOT EXISTS ix_compras_numero_compra ON compras (numero_compra);
CREATE INDEX IF NOT EXISTS ix_compras_cliente_id_estado ON compras (cliente_id, estado);

CREATE TABLE IF NOT EXISTS pagos (
    id                  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_transaccion  varchar(20)   NOT NULL,
    compra_id           integer       NOT NULL REFERENCES compras (id),
    medio_pago          varchar(20)   NOT NULL,
    banco               varchar(60),
    tipo_cuenta         varchar(30),
    correo_comprobante  varchar(200)  NOT NULL,
    valor               numeric(18,2) NOT NULL,
    estado              varchar(20)   NOT NULL,
    instrumento         varchar(200),
    referencia_pasarela varchar(100),
    codigo_fallo        varchar(20),
    mensaje_fallo       varchar(300),
    codigo_acuse_sso    varchar(60),
    acuse_sso_en        timestamptz,
    creado_en           timestamptz   NOT NULL,
    completado_en       timestamptz,
    CONSTRAINT ck_pagos_estado CHECK (estado IN ('Iniciado', 'Aprobado', 'RechazadoBanco', 'RechazadoSso', 'Vencido'))
);
CREATE UNIQUE INDEX IF NOT EXISTS ix_pagos_codigo_transaccion ON pagos (codigo_transaccion);
CREATE INDEX IF NOT EXISTS ix_pagos_compra_id ON pagos (compra_id);
-- Anti doble pago: un solo cobro en vuelo por compra.
CREATE UNIQUE INDEX IF NOT EXISTS ux_pagos_un_iniciado_por_compra ON pagos (compra_id) WHERE estado = 'Iniciado';

CREATE TABLE IF NOT EXISTS mensajes_salida (
    id                 integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo               varchar(80)  NOT NULL,
    contenido          jsonb        NOT NULL,
    agregado_id        integer,
    creado_en          timestamptz  NOT NULL,
    proximo_intento_en timestamptz  NOT NULL,
    procesado_en       timestamptz,
    intentos           integer      NOT NULL DEFAULT 0,
    ultimo_error       varchar(500)
);
CREATE INDEX IF NOT EXISTS ix_mensajes_salida_pendientes ON mensajes_salida (proximo_intento_en, creado_en) WHERE procesado_en IS NULL;
CREATE INDEX IF NOT EXISTS ix_mensajes_salida_agregado_id ON mensajes_salida (agregado_id);
